#!/usr/bin/env node
/* build-site.js — assemble the Netlify publish directory from an explicit
 * allowlist. Run after gen-config.js.
 *
 * WHY THIS EXISTS (and why redirect rules were not enough)
 * Publishing the repo root exposed every internal file: design docs, specs,
 * build scripts, the reference/ College Board PDFs. Redirect rules in
 * netlify.toml looked like they fixed it, but measured against the live site:
 *
 *     /tests/injection-proof.js  -> 404   (redirect matched)
 *     /TESTS/injection-proof.js  -> 200   (file served!)
 *
 * Netlify matches redirect `from` paths CASE-SENSITIVELY while serving files
 * CASE-INSENSITIVELY. A blocklist therefore cannot work: every rule is
 * bypassable by changing capitalisation, and an n-character path has 2^n
 * variants. The only robust fix is deny-by-default — don't put the files in
 * the publish directory at all. Nothing here can be reached by any URL in any
 * capitalisation, because it simply is not deployed.
 *
 * Adding a file the app needs? Add it to ALLOW below. The build fails if
 * index.html references something that is not on the list, so a forgotten
 * entry surfaces as a red build rather than a 404 in a student's browser.
 */
"use strict";
const fs = require("fs");
const path = require("path");

const OUT = "_site";

/* Everything the running app requires — and nothing else. */
const ALLOW = [
  "index.html",
  "404.html",
  "styles.css",
  "app.js",
  "attempts.js",
  "dashboard.js",
  "grading.js",
  "render.js",
  "skilldomains.js",
  "testdata/manifest.js",
  "testdata/archive/index.js",   // which superseded builds exist (tiny, startup)
  "testdata/bank-manifest.js",   // bank lane (startup, tiny) — banks are NOT tests
  "testdata/bank-index.js",      // the set-builder question index (startup)
  "testdata/dedup-index.js",     // canonical-id index: dashboard only, fetched lazily (never at
                                 // startup, never by a sitting). Emitted by test-bank-repo
                                 // dedup_gate.py --library --emit-platform; a missing file is a
                                 // red build, not a silent loss of the seen/unseen marks.
  "config.js",    // generated by gen-config.js, which must run first
  "_headers"      // only takes effect inside the publish directory
];

function die(lines){
  console.error("\n==================================================");
  console.error(" BUILD FAILED — publish directory not assembled");
  console.error("==================================================");
  lines.forEach(l => console.error(" " + l));
  console.error("");
  process.exit(1);
}

/* --- every local asset index.html asks for must be allowlisted --- */
let html = "";
try{ html = fs.readFileSync("index.html", "utf8"); }
catch(e){ die(["index.html is missing from the checkout."]); }

const referenced = [];
const re = /(?:src|href)\s*=\s*"([^"]+)"/g;
let m;
while((m = re.exec(html)) !== null){
  const v = m[1];
  if(/^(https?:)?\/\//i.test(v) || v.startsWith("data:") || v.startsWith("#")) continue;
  referenced.push(v.replace(/^\.?\//, ""));
}
const missingFromAllow = referenced.filter(r => ALLOW.indexOf(r) === -1);
if(missingFromAllow.length){
  die(["index.html references files that are not in build-site.js ALLOW:",
       "  " + missingFromAllow.join(", "),
       "Add them to ALLOW (or drop the reference) and rebuild.",
       "Without this the deploy would 404 them in students' browsers."]);
}

/* --- assemble --- */
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });

const copied = [], absent = [];
for(const name of ALLOW){
  if(!fs.existsSync(name)){ absent.push(name); continue; }
  const dest = path.join(OUT, name);
  fs.mkdirSync(path.dirname(dest), { recursive: true });   // allows testdata/x.js
  fs.copyFileSync(name, dest);
  copied.push(name);
}

/* Every test in the manifest ships. These are fetched at runtime rather than
   referenced from index.html, so the reference scan above cannot see them —
   the manifest is the list of what must exist, and a test named there but
   missing from disk would 404 mid-sitting. Fail the build instead. */
const TESTDATA_DIR = "testdata";
let manifestIds = [];
try{
  const mf = fs.readFileSync(path.join(TESTDATA_DIR, "manifest.js"), "utf8");
  const ids = mf.match(/"testId"\s*:\s*"([^"]+)"/g) || [];
  manifestIds = ids.map(s => s.replace(/.*"testId"\s*:\s*"/, "").replace(/"$/, ""));
}catch(e){
  die(["testdata/manifest.js is missing or unreadable — the app cannot start without it."]);
}
if(!manifestIds.length) die(["testdata/manifest.js lists no tests."]);
const missingTests = manifestIds.filter(id => !fs.existsSync(path.join(TESTDATA_DIR, id + ".js")));
if(missingTests.length){
  die(["Tests listed in the manifest have no testdata file: " + missingTests.join(", "),
       "A student starting one of these would hit a 404 mid-sitting."]);
}
fs.mkdirSync(path.join(OUT, TESTDATA_DIR), { recursive: true });
manifestIds.forEach(id => {
  const rel = path.join(TESTDATA_DIR, id + ".js");
  fs.copyFileSync(rel, path.join(OUT, rel));
  copied.push(rel);
});

/* Every bank the bank-manifest lists ships too, exactly as tests do: bank
   content (testdata/<bankId>.js) is lazy-fetched at runtime, so the
   reference scan can't see it — the bank manifest is the list of what must
   exist, and a bank named there but missing from disk would 404 the moment
   a practice set resolved its questions. Fail the build instead. Note the
   deliberate parallel WITHOUT a merge: bankIds come from bank-manifest.js
   ("bankId"), never from manifest.js ("testId") — the two lists stay
   disjoint by construction (tests/bank-isolation.test.js proves it). */
let bankIds = [];
try{
  const bmf = fs.readFileSync(path.join(TESTDATA_DIR, "bank-manifest.js"), "utf8");
  const ids = bmf.match(/"bankId"\s*:\s*"([^"]+)"/g) || [];
  bankIds = [...new Set(ids.map(s => s.replace(/.*"bankId"\s*:\s*"/, "").replace(/"$/, "")))];
}catch(e){
  die(["testdata/bank-manifest.js is missing or unreadable — the set builder cannot start without it."]);
}
const missingBanks = bankIds.filter(id => !fs.existsSync(path.join(TESTDATA_DIR, id + ".js")));
if(missingBanks.length){
  die(["Banks listed in the bank manifest have no testdata file: " + missingBanks.join(", "),
       "A practice set drawing on one of these would 404 at start."]);
}
bankIds.forEach(id => {
  const rel = path.join(TESTDATA_DIR, id + ".js");
  fs.copyFileSync(rel, path.join(OUT, rel));
  copied.push(rel);
});

/* Every ARCHIVED build the index lists ships too — Review Mode and resume
   pin attempts to the build they were sat on, and a listed-but-missing file
   would 404 exactly where the student expects their review. The index and
   the files on disk must agree in BOTH directions; drift means someone
   changed testdata/archive/ by hand — run `node archive-testdata.js`. */
const ARCHIVE_DIR = path.join(TESTDATA_DIR, "archive");
let archiveFiles = [];
try{
  const ix = fs.readFileSync(path.join(ARCHIVE_DIR, "index.js"), "utf8");
  const m = ix.match(/window\.TEST_ARCHIVE_INDEX\s*=\s*(\{[\s\S]*?\});/);
  if(!m) die(["testdata/archive/index.js is unparseable — run `node archive-testdata.js`."]);
  const idx = JSON.parse(m[1].replace(/,\s*}/g, "}"));
  archiveFiles = Object.keys(idx).sort().reduce((acc, id) =>
    acc.concat(idx[id].map(ver => id + "@" + ver + ".js")), []);
}catch(e){
  die(["testdata/archive/index.js is missing or unreadable: " + e.message,
       "Run `node archive-testdata.js` and commit its output."]);
}
const onDisk = fs.readdirSync(ARCHIVE_DIR)
  .filter(f => f.endsWith(".js") && f !== "index.js").sort();
const unlisted = onDisk.filter(f => archiveFiles.indexOf(f) === -1);
const missingArchives = archiveFiles.filter(f => !fs.existsSync(path.join(ARCHIVE_DIR, f)));
if(unlisted.length || missingArchives.length){
  die([].concat(
    missingArchives.length ? ["testdata/archive/index.js lists builds with no file: " + missingArchives.join(", ")] : [],
    unlisted.length ? ["testdata/archive/ has builds the index doesn't list: " + unlisted.join(", ")] : [],
    ["The archive and its index have drifted — run `node archive-testdata.js` and commit."]));
}
fs.mkdirSync(path.join(OUT, ARCHIVE_DIR), { recursive: true });
archiveFiles.forEach(f => {
  const rel = path.join(ARCHIVE_DIR, f);
  fs.copyFileSync(rel, path.join(OUT, rel));
  copied.push(rel);
});

/* Every IMAGE the deploy ships must be one the renderer accepts (2026-10-18,
   IMAGE-CHOICES-SPEC §2.4). app.js's imageSourceOk refuses a source outside
   the data:image grammar or whose decoded bytes are not the type it
   declares, and the student then sees "Figure unavailable" or "Image
   unavailable" in its place. The test-bank converter checks image CHOICES
   at least that hard but stem FIGURES against the grammar alone, so a
   mislabelled or non-SVG figure can export cleanly. This makes that a red
   build naming the item, the same posture as a manifest entry with no file.
   The guard is taken from app.js itself (tests/extract-helper.js, the
   extraction the node suites use), so the build checks exactly what the
   renderer runs, and "renders" means what the renderer does with a figure
   (a frame for any truthy q.figure) and a choice (the image path for any
   non-string entry). Current builds and banks are FATAL: the fix is a
   re-export. An ARCHIVED build is byte-pinned to the commit it was served
   from and cannot be re-exported, so a refusal there is a WARNING naming
   it: Review Mode and resume on that build would show the placeholder. */
{
  const vm = require("vm");
  /* the guard decodes with the global atob, exactly as the browser does
     (Node 16+). Without it every image would be "refused" — say why instead */
  if(typeof atob !== "function")
    die(["The image guard needs Node 16 or later (global atob); this build runs Node " + process.version + "."]);
  let guard;
  try{
    const { extractFn, extractConst } = require("./tests/extract-helper");
    const appSrc = fs.readFileSync("app.js", "utf8");
    guard = new Function([extractConst(appSrc, "CHOICE_IMAGE_RE"), extractFn(appSrc, "imageSourceOk"),
      extractFn(appSrc, "isImageChoice"), extractFn(appSrc, "choiceImageSrc"), extractFn(appSrc, "figureSrc")].join("\n") +
      "\nreturn { choiceImageSrc, figureSrc };")();
  }catch(e){
    die(["Could not take the image guard from app.js (" + e.message + ").",
         "build-site.js checks every shipped image with app.js's own choiceImageSrc and figureSrc."]);
  }
  /* SELF-CHECK before any test data is judged: the guard as extracted must
     accept known-good images of every kind and refuse a known-bad one. The
     extraction above names its pieces by hand, and imageSourceOk swallows
     every exception as a refusal, so a helper or const added beside it in a
     later refactor would otherwise read as "every SVG refused — fix the item
     in the test-bank repo" (review 2026-10-18), pointing the fixer at the
     wrong repo. */
  {
    const NS = "http://www.w3.org/2000/svg";
    const b64 = s => Buffer.from(s, "latin1").toString("base64");
    const good = [
      "data:image/png;base64," + b64("\x89PNG\r\n\x1A\n\x00\x00\x00\x0DIHDR"),
      "data:image/jpeg;base64," + b64("\xFF\xD8\xFF\xE0\x00\x10JFIF\x00"),
      "data:image/svg+xml;base64," + b64('<svg xmlns="' + NS + '"/>'),
      "data:image/svg+xml;base64," + b64('<s:svg xmlns:s="' + NS + '"/>'),
      "data:image/svg+xml;base64," + b64('<?xml version="1.0"?>\n<!-- c -->\n<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" ' +
        '"http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">\n<svg xmlns="' + NS + '"/>')];
    const bad = "data:image/jpeg;base64," + b64("\x89PNG\r\n\x1A\n\x00\x00\x00\x0DIHDR");
    const wrong = good.filter(u => guard.figureSrc({ figure: u }) !== u || guard.choiceImageSrc({ image: u }) !== u)
      .map(u => "refuses a known-good " + u.slice(11, u.indexOf(";")))
      .concat(guard.figureSrc({ figure: bad }) === null && guard.choiceImageSrc({ image: bad }) === null ? [] : ["accepts PNG bytes labelled jpeg"]);
    if(wrong.length)
      die(["The image guard taken from app.js is not working here: it " + wrong.join("; it ") + ".",
           "This is build-site.js's extraction, not the test data: a helper or const beside imageSourceOk",
           "in app.js must be added to the list build-site.js extracts."]);
  }
  const tally = { figures: 0, choices: 0, live: { png: 0, jpeg: 0, "svg+xml": 0, other: 0 }, archived: { png: 0, jpeg: 0, "svg+xml": 0, other: 0 } };
  const kind = v => { const t = /^data:image\/(png|jpeg|svg\+xml);/.exec(typeof v === "string" ? v : ""); return t ? t[1] : "other"; };
  const audit = (rel, id, bank, archived) => {
    const c = { window: { __TESTDATA__: {}, __BANKDATA__: {} } };
    vm.createContext(c);
    vm.runInContext(fs.readFileSync(rel, "utf8"), c, { filename: rel });
    const data = bank ? c.window.__BANKDATA__[id] : c.window.__TESTDATA__[id];
    if(!data) return [rel + " does not register " + id];
    const qs = bank ? (data.questions || []) : [].concat(...(data.modules || []).map(m => m.questions || []));
    const bad = [];
    qs.forEach(q => {
      if(!q) return;
      const where = rel.replace(/\\/g, "/") + " " + (q.id || q.qid);
      const head = v => typeof v === "string" ? v.slice(0, 30) + "…" : String(v);
      if(q.figure){
        tally.figures++; tally[archived ? "archived" : "live"][kind(q.figure)]++;
        if(guard.figureSrc(q) !== q.figure) bad.push(where + " figure (" + head(q.figure) + ")");
      }
      (Array.isArray(q.choices) ? q.choices : []).forEach((ch, i) => {
        if(typeof ch === "string") return;
        tally.choices++;
        if(guard.choiceImageSrc(ch) === null) bad.push(where + " choice " + "ABCD".charAt(i) + " (" + head(ch && ch.image) + ")");
      });
    });
    return bad;
  };
  const fatal = [].concat(
    ...manifestIds.map(id => audit(path.join(TESTDATA_DIR, id + ".js"), id, false, false)),
    ...bankIds.map(id => audit(path.join(TESTDATA_DIR, id + ".js"), id, true, false)));
  const archived = [].concat(...archiveFiles.map(f => audit(path.join(ARCHIVE_DIR, f), f.split("@")[0], false, true)));
  if(fatal.length){
    die(["Images the renderer would refuse — students would see \"Figure unavailable\" / \"Image unavailable\":"]
      .concat(fatal.slice(0, 20).map(b => "  " + b), fatal.length > 20 ? ["  … and " + (fatal.length - 20) + " more"] : [],
        ["A source must match the data:image grammar AND its decoded bytes must be the type it declares",
         "(app.js imageSourceOk; IMAGE-CHOICES-SPEC.md §2.4). Fix the item in the test-bank repo and re-export."]));
  }
  if(archived.length){
    console.warn("build-site.js: WARNING — archived builds hold images the renderer refuses (Review Mode / resume on them show the placeholder): " +
      archived.slice(0, 10).join("; ") + (archived.length > 10 ? "; … and " + (archived.length - 10) + " more" : ""));
  }
  const types = t => "png " + t.png + ", jpeg " + t.jpeg + ", svg+xml " + t["svg+xml"] + (t.other ? ", other " + t.other : "");
  console.log("build-site.js: image guard — " + tally.figures + " figures and " + tally.choices +
    " image choices checked across current, bank and archived builds; every current and bank image passes");
  console.log("  figures by type: current and bank (" + types(tally.live) + "); archived (" + types(tally.archived) + ")");
}

/* The canonical-id index records the build of every form and bank it was
   generated against. Drift against the manifests is NOT fatal — the
   dashboard names it in its own notice and degrades to "not indexed" /
   "may be stale" marks — but a deploy log that says so is the earlier,
   cheaper signal that `dedup_gate.py --library --emit-platform` was
   skipped after an export or a testVersion bump.
   Every parse below FAILS LOUDLY: from 2026-09-07 to 2026-09-30 the bank
   pattern had lost its backslashes (`window.BANK_MANIFESTs*=s*…`), matched
   nothing, and a silent `bmm ? … : []` turned that into "no banks to
   compare" — the bank half of this check never ran and nothing said so.
   A pattern that stops matching is now a warning naming the file, and
   tests/build-site-drift.test.js runs this script on a copy of the tree
   with planted drift (and on the unmodified tree, which must stay quiet). */
try{
  const readAssigned = (file, re, what) => {
    const m = fs.readFileSync(path.join(TESTDATA_DIR, file), "utf8").match(re);
    if(!m) throw new Error(TESTDATA_DIR + "/" + file + " does not match the " + what + " pattern");
    return JSON.parse(m[1]);
  };
  const ref = readAssigned("dedup-index.js", /window\.DEDUP_INDEX\s*=\s*(\{[\s\S]*\});\s*$/, "window.DEDUP_INDEX = {…};").reference || {};
  const forms = Array.isArray(ref.forms) ? ref.forms : [];
  const banks = Array.isArray(ref.banks) ? ref.banks : [];
  const manifest = readAssigned("manifest.js", /window\.TEST_MANIFEST\s*=\s*(\[[\s\S]*\]);\s*$/, "window.TEST_MANIFEST = […];");
  const bankManifest = readAssigned("bank-manifest.js", /window\.BANK_MANIFEST\s*=\s*(\[[\s\S]*\]);\s*$/, "window.BANK_MANIFEST = […];");
  if(!Array.isArray(manifest) || !Array.isArray(bankManifest))
    throw new Error("manifest.js / bank-manifest.js did not parse to a list");
  const drift = [];
  manifest.forEach(t => {
    const f = forms.find(x => x && x.testId === t.testId);
    if(!f) drift.push(t.testId + " (not in the index)");
    else if(f.testVersion && t.testVersion && f.testVersion !== t.testVersion)
      drift.push(t.testId + " (index " + f.testVersion + ", manifest " + t.testVersion + ")");
  });
  bankManifest.forEach(b => {
    const f = banks.find(x => x && x.bankId === b.bankId);
    if(!f) drift.push(b.bankId + " (bank not in the index)");
    else if(f.bankVersion && b.bankVersion && f.bankVersion !== b.bankVersion)
      drift.push(b.bankId + " (index " + f.bankVersion + ", bank manifest " + b.bankVersion + ")");
  });
  if(drift.length){
    console.warn("build-site.js: WARNING — testdata/dedup-index.js is behind the manifest: " + drift.join(", "));
    console.warn("  The dashboard will show a stale-index notice. Re-run dedup_gate.py --library --emit-platform in the test-bank repo.");
  }
}catch(e){
  console.warn("build-site.js: WARNING — could not compare testdata/dedup-index.js with the manifest: " + e.message);
}
if(absent.length){
  die(["These allowlisted files are missing from the checkout: " + absent.join(", "),
       absent.indexOf("config.js") !== -1
         ? "config.js is generated by gen-config.js — it must run before this script."
         : "Check the repository contents."]);
}

/* --- prove the result contains nothing else --- */
function walk(dir, base){
  return fs.readdirSync(dir).reduce((acc, f) => {
    const full = path.join(dir, f);
    const rel = base ? base + "/" + f : f;
    return acc.concat(fs.statSync(full).isDirectory() ? walk(full, rel) : [rel]);
  }, []);
}
const shipped = walk(OUT, "").sort();
// allowlisted outright, a manifest-listed test, or an index-listed archived
// build — all deliberately copied above
const permitted = ALLOW.concat(manifestIds.map(id => TESTDATA_DIR + "/" + id + ".js"))
  .concat(bankIds.map(id => TESTDATA_DIR + "/" + id + ".js"))
  .concat(archiveFiles.map(f => TESTDATA_DIR + "/archive/" + f));
const unexpected = shipped.filter(f => permitted.indexOf(f) === -1);
if(unexpected.length) die(["Unexpected files in " + OUT + ": " + unexpected.join(", ")]);

console.log("build-site.js: publish directory " + OUT + "/ contains " + shipped.length + " file(s):");
shipped.forEach(f => console.log("  " + f));
console.log("  -> everything else in the repo (docs, specs, build scripts,");
console.log("     reference/, supabase/, tests/) is NOT deployed.");
